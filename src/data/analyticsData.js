// Timeline generator helpers for 7d, 30d, 90d (3m), 12m (1y)
const generateTimeline = (days) => {
  const dates = []
  const now = new Date(2026, 5, 24) // Base reference date Jun 24, 2026
  
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(now)
    if (days <= 30) {
      d.setDate(now.getDate() - i)
      dates.push({
        date: d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
        likes: Math.floor(350 + Math.sin(i * 0.5) * 180 + Math.random() * 120),
        comments: Math.floor(45 + Math.cos(i * 0.5) * 25 + Math.random() * 20),
        shares: Math.floor(30 + Math.sin(i * 0.4) * 20 + Math.random() * 15),
        reach: Math.floor(3500 + Math.sin(i * 0.3) * 1200 + Math.random() * 800),
        impressions: Math.floor(6200 + Math.sin(i * 0.3) * 2200 + Math.random() * 1400),
        followers: Math.floor(41200 + (days - i) * 55 + Math.floor(Math.random() * 25)),
      })
    } else if (days <= 90) {
      if (i % 3 === 0) { // Every 3 days for 3 months view
        d.setDate(now.getDate() - i)
        dates.push({
          date: d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
          likes: Math.floor(1100 + Math.sin(i * 0.2) * 500 + Math.random() * 300),
          comments: Math.floor(140 + Math.cos(i * 0.2) * 60 + Math.random() * 40),
          shares: Math.floor(95 + Math.sin(i * 0.2) * 45 + Math.random() * 30),
          reach: Math.floor(11500 + Math.sin(i * 0.15) * 4000 + Math.random() * 2000),
          impressions: Math.floor(21000 + Math.sin(i * 0.15) * 7000 + Math.random() * 3500),
          followers: Math.floor(38500 + (90 - i) * 48 + Math.floor(Math.random() * 30)),
        })
      }
    } else { // 12 Months
      if (i % 30 === 0) {
        d.setMonth(now.getMonth() - Math.floor(i / 30))
        dates.push({
          date: d.toLocaleDateString('en-US', { month: 'short' }),
          likes: Math.floor(9800 + Math.random() * 3000),
          comments: Math.floor(1250 + Math.random() * 400),
          shares: Math.floor(820 + Math.random() * 250),
          reach: Math.floor(95000 + Math.random() * 30000),
          impressions: Math.floor(185000 + Math.random() * 50000),
          followers: Math.floor(28000 + ((365 - i) / 30) * 1230),
        })
      }
    }
  }
  return dates
}

